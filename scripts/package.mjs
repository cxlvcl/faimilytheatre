import { cp, mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const stamp = new Date().toISOString().replace(/[:.]/g, '-')
const release = join(root, 'release', stamp)
const publicRoot = join(release, 'public_html')
const privateRoot = join(release, 'private')
await mkdir(publicRoot, { recursive: true })
await mkdir(privateRoot, { recursive: true })
for (const name of ['assets', 'media', 'fonts', 'favicon.ico', 'favicon-black-48.png', 'favicon-black-96.png', 'favicon-black-192.png', 'favicon-white-48.png', 'favicon-white-96.png', 'favicon-white-192.png', 'apple-touch-icon.png']) await cp(join(root, 'web/dist', name), join(publicRoot, name), { recursive: true })
await cp(join(root, 'web/dist/.vite/manifest.json'), join(privateRoot, 'manifest.json'))
await cp(join(root, 'web/dist/.vite/ssr'), join(privateRoot, 'ssr'), { recursive: true })
await cp(join(root, 'api'), join(privateRoot, 'api'), { recursive: true, filter: path => !path.endsWith('/config.php') })
await cp(join(root, 'database'), join(privateRoot, 'database'), { recursive: true })
await cp(join(root, 'cron'), join(privateRoot, 'cron'), { recursive: true })
await mkdir(join(publicRoot, 'api'))
await mkdir(join(publicRoot, 'uploads'))
await cp(join(root, 'uploads/.htaccess'), join(publicRoot, 'uploads/.htaccess'))
await writeFile(join(publicRoot, 'index.php'), "<?php require dirname(__DIR__) . '/private/api/seo/index.php';\n")
await writeFile(join(publicRoot, 'api/index.php'), "<?php require dirname(__DIR__, 2) . '/private/api/index.php';\n")
await cp(join(root, 'deployment/public-api.htaccess'), join(publicRoot, 'api/.htaccess'))
for (const name of ['robots', 'sitemap']) await writeFile(join(publicRoot, `${name}.php`), `<?php require dirname(__DIR__) . '/private/api/seo/${name}.php';\n`)
await cp(join(root, 'deployment/public.htaccess'), join(publicRoot, '.htaccess'))
await cp(join(root, 'deployment/config.example.php'), join(privateRoot, 'config.example.php'))
await writeFile(join(privateRoot, '.htaccess'), 'Require all denied\n')
await cp(join(root, 'docs'), join(release, 'docs'), { recursive: true })
const manifest = JSON.parse(await readFile(join(privateRoot, 'manifest.json'), 'utf8'))
if (!manifest['index.html']?.file) throw new Error('Vite manifest entry is missing')
if (process.argv.includes('--json')) console.log(JSON.stringify({ release, publicRoot, privateRoot }))
else console.log(`Пакет для REG.RU: ${release}\nБаза, секреты и пользовательские загрузки НЕ включены.`)
